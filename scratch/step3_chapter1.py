def configure_chapter_section_page_numbering(section, start_page=None):
    """
    ตั้งค่าเลขหน้ามุมบนขวาสำหรับส่วนเนื้อหา (1, 2, 3...)
    โดยไม่แสดงเลขหน้าในหน้าแรกของบท (different_first_page_header_footer = True)
    ตามเกณฑ์คู่มือรูปแบบรายงานวิจัย มรย. ข้อ 6
    """
    section.different_first_page_header_footer = True

    # หน้าแรกของบท: ไม่แสดงเลขหน้า
    first_header = section.first_page_header
    first_header.is_linked_to_previous = False
    p_first = first_header.paragraphs[0] if first_header.paragraphs else first_header.add_paragraph()
    p_first.text = ""

    # หน้าถัดไปของบท: แสดงเลขหน้าตัวเลขอารบิกมุมบนขวา
    header = section.header
    header.is_linked_to_previous = False
    p = header.paragraphs[0] if header.paragraphs else header.add_paragraph()
    p.text = ""
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT

    run = p.add_run()
    set_run_thai_font(run, "TH SarabunPSK", size_pt=16, bold=False)
    fldChar1 = OxmlElement("w:fldChar")
    fldChar1.set(qn("w:fldCharType"), "begin")
    instrText = OxmlElement("w:instrText")
    instrText.set(qn("xml:space"), "preserve")
    instrText.text = "PAGE"
    fldChar2 = OxmlElement("w:fldChar")
    fldChar2.set(qn("w:fldCharType"), "separate")
    fldChar3 = OxmlElement("w:fldChar")
    fldChar3.set(qn("w:fldCharType"), "end")
    run._r.append(fldChar1)
    run._r.append(instrText)
    run._r.append(fldChar2)
    run._r.append(fldChar3)

    sectPr = section._sectPr
    pgNumType = sectPr.find(qn("w:pgNumType"))
    if pgNumType is None:
        pgNumType = OxmlElement("w:pgNumType")
        cols = sectPr.find(qn("w:cols"))
        if cols is not None:
            sectPr.insert(list(sectPr).index(cols), pgNumType)
        else:
            sectPr.append(pgNumType)
    pgNumType.set(qn("w:fmt"), "decimal")
    if start_page is not None:
        pgNumType.set(qn("w:start"), str(start_page))
    else:
        if qn("w:start") in pgNumType.attrib:
            del pgNumType.attrib[qn("w:start")]


def add_chapter_heading(doc, chapter_num_str, chapter_title_str):
    add_centered_line(
        doc,
        chapter_num_str,
        size_pt=20,
        bold=True,
        space_before_pt=0,
        space_after_pt=6,
        line_spacing=1.0,
    )
    add_centered_line(
        doc,
        chapter_title_str,
        size_pt=20,
        bold=True,
        space_before_pt=0,
        space_after_pt=14,
        line_spacing=1.0,
    )


def add_section_heading(doc, heading_text, space_before_pt=12, space_after_pt=6):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.space_before = Pt(space_before_pt)
    p.paragraph_format.space_after = Pt(space_after_pt)
    p.paragraph_format.line_spacing = 1.15
    p.paragraph_format.keep_with_next = True
    run = p.add_run(thai_word_wrap(heading_text))
    set_run_thai_font(run, "TH SarabunPSK", size_pt=18, bold=True)
    return p


def add_numbered_item(doc, number_prefix, item_text, bold_prefix=False, space_after_pt=4):
    """
    สร้างรายการย่อยแบบ Hanging Indent (เช่น 1.3.1 ..., 1.7.1 ...)
    ให้บรรทัดที่ 2 ตรงกับข้อความหลังหมายเลขเหมือนเล่มตัวอย่าง AEGis
    พร้อมจัดข้อความแบบ Thai Justify ให้ชิดขอบขวาเสมอกัน
    """
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.THAI_JUSTIFY
    p.paragraph_format.left_indent = Inches(0.55)
    p.paragraph_format.first_line_indent = Inches(-0.55)
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(space_after_pt)
    p.paragraph_format.line_spacing = 1.15

    tab_stops = p.paragraph_format.tab_stops
    tab_stops.add_tab_stop(Inches(0.55))

    r_num = p.add_run(number_prefix + "\t")
    set_run_thai_font(r_num, "TH SarabunPSK", size_pt=16, bold=bold_prefix)

    r_txt = p.add_run(thai_word_wrap(item_text))
    set_run_thai_font(r_txt, "TH SarabunPSK", size_pt=16, bold=False)
    return p


def add_term_definition(doc, number_prefix, term_name, definition_text, space_after_pt=4):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.THAI_JUSTIFY
    p.paragraph_format.left_indent = Inches(0.55)
    p.paragraph_format.first_line_indent = Inches(-0.55)
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(space_after_pt)
    p.paragraph_format.line_spacing = 1.15

    tab_stops = p.paragraph_format.tab_stops
    tab_stops.add_tab_stop(Inches(0.55))

    r_num = p.add_run(number_prefix + "\t")
    set_run_thai_font(r_num, "TH SarabunPSK", size_pt=16, bold=False)

    r_term = p.add_run(thai_word_wrap(term_name) + " ")
    set_run_thai_font(r_term, "TH SarabunPSK", size_pt=16, bold=True)

    r_def = p.add_run(thai_word_wrap(definition_text))
    set_run_thai_font(r_def, "TH SarabunPSK", size_pt=16, bold=False)
    return p


