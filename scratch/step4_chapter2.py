def format_academic_table(table):
    """
    ตั้งค่าเส้นขอบตารางแบบวิชาการ มีเส้นแบ่งคอลัมน์แนวตั้ง (insideV) และแนวนอน (insideH) ครบถ้วน
    สอดคล้องกับรูปแบบคู่มือวิจัย มหาวิทยาลัยราชภัฏยะลา และตัวอย่าง Data Dictionary
    """
    tblPr = table._tbl.tblPr
    tblBorders = OxmlElement("w:tblBorders")

    for border_name, val, sz in [
        ("top", "single", "8"),
        ("bottom", "single", "8"),
        ("left", "single", "4"),
        ("right", "single", "4"),
        ("insideH", "single", "4"),
        ("insideV", "single", "4"),
    ]:
        border = OxmlElement(f"w:{border_name}")
        border.set(qn("w:val"), val)
        border.set(qn("w:sz"), sz)
        border.set(qn("w:space"), "0")
        border.set(qn("w:color"), "000000")
        tblBorders.append(border)

    tblPr.append(tblBorders)


